            layout.AddChild(background);

            var zone = new PanelContainer { PanelOverride = new StyleBoxFlat { BackgroundColor = solvedThis ? FlowCheckpointHit : ZoneColor } };
            layout.AddChild(zone);

            var markerBox = new StyleBoxFlat { BackgroundColor = MarkerColor };
            var marker = new PanelContainer { PanelOverride = markerBox, Visible = !solvedThis };
