            {
                NormalColor = new Color(0f, 0f, 0f, 0f),
                Disabled = solvedThis,
                MinSize = new Vector2(300f, 34f),
            };
            clickCatcher.UpdateVisual();
            clickCatcher.OnPressed += () => OnGridClick?.Invoke(index);
            layout.AddChild(clickCatcher);

