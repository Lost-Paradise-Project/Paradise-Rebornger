    private void BuildMemoryGrid(DiskDecryptorBoundUserInterfaceState state)
    {
        PuzzleGrid.Columns = 4;
        GridHintLabel.Text = Loc.GetString("disk-decryptor-memory-hint");

        var symbols = state.MemoryVisibleSymbols ?? new List<int>();
        var matched = state.MemoryMatched;
        var pairsFound = (matched?.Count(m => m) ?? 0) / 2;
        GridInfoLabel.Text = Loc.GetString("disk-decryptor-memory-found", ("found", pairsFound), ("total", symbols.Count / 2));

        for (var i = 0; i < symbols.Count; i++)
        {
            var index = i;
            var isMatched = matched != null && index < matched.Count && matched[index];
            var value = symbols[index];
            var faceUp = value >= 0;
            var color = isMatched ? CardMatched : faceUp ? CardFlipped : CardHidden;
            var text = faceUp ? (value + 1).ToString() : "?";
            var button = new Button
            {
                MinSize = new Vector2(48, 48),
                Modulate = color,
                Disabled = isMatched,
                Text = text,
            };
            button.OnPressed += _ => OnGridClick?.Invoke(index);
            PuzzleGrid.AddChild(button);
        }
    }

    private void BuildPipeGrid(DiskDecryptorBoundUserInterfaceState state)
    {
        PuzzleGrid.Columns = Math.Max(1, state.PipeSize);
        GridHintLabel.Text = Loc.GetString("disk-decryptor-pipe-hint");

        var baseMask = state.PipeBaseMask ?? new List<int>();
        var rotation = state.PipeRotation ?? new List<int>();
        var buttonSize = GridButtonSize(state.PipeSize);
        var solved = true;
        for (var i = 0; i < baseMask.Count; i++)
        {
            if (baseMask[i] != 0 && RotateCwClientSide(baseMask[i], rotation[i]) != baseMask[i])
            {
                solved = false;
                break;
            }
        }
        GridInfoLabel.Text = Loc.GetString(solved ? "disk-decryptor-pipe-connected" : "disk-decryptor-pipe-broken");

        for (var i = 0; i < baseMask.Count; i++)
        {
            var index = i;
            var mask = baseMask[index];
            var isEndpoint = index == state.PipeStartIndex || index == state.PipeEndIndex;
            var background = isEndpoint ? PipeEndpointBg : PipeBackground;
            var cell = new PipeCell { MinSize = new Vector2(buttonSize, buttonSize) };

            if (mask == 0)
            {
                cell.SetVisual(0, PipeUnsolved, PipeBackground, false);
            }
            else
            {
                var current = RotateCwClientSide(mask, rotation[index]);
                var cellSolved = current == mask;
                cell.SetVisual(current, cellSolved ? PipeSolved : PipeUnsolved, background, true);
                cell.OnPressed += () => OnGridClick?.Invoke(index);
            }

            PuzzleGrid.AddChild(cell);
        }
    }

    private static int RotateCwClientSide(int mask, int steps)
    {
        for (var i = 0; i < steps; i++)
        {
            mask = ((mask << 1) | (mask >> 3)) & 0b1111;
        }

        return mask;
    }

    private void BuildPatternGrid(DiskDecryptorBoundUserInterfaceState state)
    {
        PuzzleGrid.Columns = Math.Max(1, state.PatternSize);
        GridHintLabel.Text = Loc.GetString("disk-decryptor-pattern-hint");

        var targets = state.PatternTargets ?? new List<bool>();
        var found = state.PatternFound ?? new List<bool>();
        GridInfoLabel.Text = Loc.GetString(
            "disk-decryptor-pattern-progress",
            ("found", found.Count(f => f)),
            ("total", targets.Count(t => t)));

        _patternButtons.Clear();
        _patternRevealing = _gameTiming.CurTime < state.PatternRevealEndTime;
        _patternRevealEnd = state.PatternRevealEndTime;

        var buttonSize = GridButtonSize(state.PatternSize);
        for (var i = 0; i < targets.Count; i++)
        {
            var index = i;
            var isTarget = targets[i];
            var isFound = found.Count > i && found[i];
            var color = isFound ? PatternFoundColor : _patternRevealing && isTarget ? PatternShown : PatternHidden;
            var button = new SciFiButton
            {
                MinSize = new Vector2(buttonSize, buttonSize),
                NormalColor = color,
                Disabled = isFound || _patternRevealing,
            };
            button.UpdateVisual();
            button.OnPressed += () => OnGridClick?.Invoke(index);
            PuzzleGrid.AddChild(button);

            if (!isFound)
                _patternButtons.Add(button);
        }
    }

