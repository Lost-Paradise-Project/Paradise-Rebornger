            LayoutContainer.SetPosition(marker, Vector2.Zero);
            LayoutContainer.SetPosition(clickCatcher, Vector2.Zero);

            BandsContainer.AddChild(wrapper);

            if (!solvedThis)
            {
                _bandRows.Add((
