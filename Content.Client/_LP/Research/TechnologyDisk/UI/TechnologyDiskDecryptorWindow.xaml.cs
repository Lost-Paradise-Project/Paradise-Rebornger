    public void UpdateState(DiskDecryptorBoundUserInterfaceState state)
    {
        var idle = state.Phase == DecryptorPhase.Idle;
        var manual = state.Phase == DecryptorPhase.Manual;
        var calibration = manual && state.MinigameKind == MinigameKind.Calibration;
        var grid = manual && !calibration;

        StartManualButton.Disabled = !state.HasDisk || !idle;
        StartAutoButton.Visible = state.HasProcessor;
        StartAutoButton.Disabled = !state.HasDisk || !idle;
        ClaimButton.Disabled = idle;
        LockButton.Disabled = !calibration;

        var integrityWidth = TrackWidthOf(IntegrityTrack);
        var integrityHeight = IntegrityTrack.Size.Y > 1f ? IntegrityTrack.Size.Y : 16f;
        var integrityFraction = state.Integrity / 100f;
        _integrityFill!.MinSize = new Vector2(integrityWidth * integrityFraction, integrityHeight);
        LayoutContainer.SetPosition(_integrityFill, Vector2.Zero);
        _integrityFillBox.BackgroundColor = GetBarColor(integrityFraction);

        var ledColor = state.Phase switch
        {
            DecryptorPhase.Idle => TrackColor,
            DecryptorPhase.AutoRunning => AccentTeal,
            _ when state.Integrity < 40 => AccentDanger,
            _ => AccentCyan,
        };
        ((StyleBoxFlat)StatusLed.PanelOverride!).BackgroundColor = ledColor;

        TierLabel.Visible = state.DiskTier.HasValue;
        if (state.DiskTier is { } tier)
        {
            TierLabel.Text = Loc.GetString("disk-decryptor-tier-badge", ("tier", tier));
            TierLabel.FontColorOverride = AccentAmber;
        }

        RecipeLabel.Text = string.IsNullOrEmpty(state.MaskedRecipeName) ? Loc.GetString("disk-decryptor-recipe-none")
            : Loc.GetString("disk-decryptor-recipe-hint", ("hint", state.MaskedRecipeName));
        StatusLabel.Text = GetStatusText(state).ToUpperInvariant();
        CalibrationBox.Visible = calibration;
        GridBox.Visible = grid;

        if (calibration)
        {
            var trackWidth = TrackWidthOf(CalibrationTrack);
            var trackHeight = CalibrationTrack.Size.Y > 1f ? CalibrationTrack.Size.Y : 40f;
            var zoneX = state.CalibrationZoneStart * trackWidth;
            var zoneWidthPx = state.CalibrationZoneWidth * trackWidth;
            _zoneRect!.MinSize = new Vector2(zoneWidthPx, trackHeight);
            LayoutContainer.SetPosition(_zoneRect, new Vector2(zoneX, 0));
        }

        if (grid)
            RebuildGrid(state);

        _phase = state.Phase;
        _deadline = state.Deadline;
        _secondsTotal = state.SecondsTotal;
        _minigameKind = state.MinigameKind;
        _calibrationStartTime = state.CalibrationStartTime;
        _calibrationPeriod = state.CalibrationPeriodSeconds;
    }

    private static string GetStatusText(DiskDecryptorBoundUserInterfaceState state)
    {
        if (state.Phase == DecryptorPhase.Idle)
            return Loc.GetString("disk-decryptor-status-idle");

        if (state.Phase == DecryptorPhase.AutoRunning)
            return Loc.GetString("disk-decryptor-status-auto");

        var key = state.MinigameKind switch
        {
            MinigameKind.Calibration => "disk-decryptor-status-calibration",
            MinigameKind.Circuit => "disk-decryptor-status-circuit",
            MinigameKind.LightsOut => "disk-decryptor-status-lightsout",
            MinigameKind.MemoryPairs => "disk-decryptor-status-memory",
            MinigameKind.Breach => "disk-decryptor-status-breach",
            MinigameKind.Pipe => "disk-decryptor-status-pipe",
            MinigameKind.Flow => "disk-decryptor-status-flow",
            MinigameKind.PatternRecall => "disk-decryptor-status-pattern",
            MinigameKind.CodeGuess => "disk-decryptor-status-code",
            MinigameKind.SignalJam => "disk-decryptor-status-jam",
            MinigameKind.FrequencyBands => "disk-decryptor-status-bands",
            MinigameKind.MineSweep => "disk-decryptor-status-sweep",
            _ => "disk-decryptor-status-idle",
        };

        return Loc.GetString(key, ("layer", state.CurrentLayer + 1), ("total", state.TotalLayers));
    }

    private void RebuildGrid(DiskDecryptorBoundUserInterfaceState state)
    {
        var kind = state.MinigameKind;
        var isFlow = kind == MinigameKind.Flow;
        var isCode = kind == MinigameKind.CodeGuess;
        var isBands = kind == MinigameKind.FrequencyBands;
        var isGrid = !isFlow && !isCode && !isBands;

        PuzzleGrid.Visible = isGrid;
        FlowCanvasTrack.Visible = isFlow;
        CodeRow.Visible = isCode;
        CodeSubmitFrame.Visible = isCode;
        BandsContainer.Visible = isBands;
        PuzzleGrid.RemoveAllChildren();
        SequenceRow.Visible = kind == MinigameKind.Breach;
        SweepFlagFrame.Visible = kind == MinigameKind.MineSweep;
        _lastState = state;

        GridHintLabel.FontColorOverride = kind is MinigameKind.MineSweep or MinigameKind.Breach ? AccentDanger : TextDim;

        switch (kind)
        {
            case MinigameKind.Circuit: BuildCircuitGrid(state); break;
            case MinigameKind.LightsOut: BuildLightsGrid(state); break;
            case MinigameKind.MemoryPairs: BuildMemoryGrid(state); break;
            case MinigameKind.Pipe: BuildPipeGrid(state); break;
            case MinigameKind.PatternRecall: BuildPatternGrid(state); break;
            case MinigameKind.CodeGuess: BuildCodeGuess(state); break;
            case MinigameKind.SignalJam: BuildSignalJamGrid(state); break;
            case MinigameKind.FrequencyBands: BuildFrequencyBands(state); break;
            case MinigameKind.MineSweep: BuildMineSweepGrid(state); break;
            case MinigameKind.Flow: BuildFlowNetwork(state); break;
            case MinigameKind.Breach: BuildBreachGrid(state); break;
        }

        GridInfoLabel.FontColorOverride = AccentAmber;
    }

    private void BuildCircuitGrid(DiskDecryptorBoundUserInterfaceState state)
    {
        PuzzleGrid.Columns = Math.Max(1, state.CircuitSize);
        GridHintLabel.Text = Loc.GetString("disk-decryptor-circuit-hint");
        GridInfoLabel.Text = Loc.GetString("disk-decryptor-circuit-moves", ("moves", state.CircuitMovesLeft));

        var blocked = state.CircuitBlocked;
        var path = state.CircuitPath;
        var total = state.CircuitSize * state.CircuitSize;
        var buttonSize = GridButtonSize(state.CircuitSize);

        for (var i = 0; i < total; i++)
        {
            var index = i;
            var isBlocked = blocked != null && index < blocked.Count && blocked[index];
            var inPath = path != null && path.Contains(index);
            var color = index switch
            {
                _ when index == state.CircuitStartIndex => NodeStart,
                _ when index == state.CircuitEndIndex => NodeEnd,
                _ when isBlocked => NodeBlocked,
                _ when inPath => NodePath,
                _ => NodeNormal,
            };

            AddGridButton(index, color, isBlocked, string.Empty, buttonSize);
        }
    }

