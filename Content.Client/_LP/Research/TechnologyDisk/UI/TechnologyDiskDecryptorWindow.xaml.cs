                    periods.Count > i ? periods[i] : 1f,
                    startTimes.Count > i ? startTimes[i] : TimeSpan.Zero,
                    zoneStarts.Count > i ? zoneStarts[i] : 0f,
                    zoneWidths.Count > i ? zoneWidths[i] : 0.2f));
            }
        }
    }

    private void BuildMineSweepGrid(DiskDecryptorBoundUserInterfaceState state)
    {
        PuzzleGrid.RemoveAllChildren();
        PuzzleGrid.Columns = Math.Max(1, state.SweepSize);
        GridHintLabel.Text = Loc.GetString("disk-decryptor-sweep-hint");
        UpdateSweepFlagButtonText();

        var visible = state.SweepVisible ?? new List<int>();
        var revealedCount = visible.Count(v => v >= 0);
        GridInfoLabel.Text = Loc.GetString("disk-decryptor-sweep-progress", ("count", revealedCount));

        if (revealedCount < _lastSweepRevealedCount)
            _sweepFlags.Clear();
        _lastSweepRevealedCount = revealedCount;

        var buttonSize = GridButtonSize(state.SweepSize);
        for (var i = 0; i < visible.Count; i++)
        {
            var index = i;
            var value = visible[i];
            var revealed = value >= 0;
            var flagged = !revealed && _sweepFlags.Contains(index);
            var color = revealed ? SweepSafe : flagged ? SweepFlagColor : SweepHidden;
            var text = revealed && value > 0 ? value.ToString() : flagged ? "⚑" : string.Empty;
            var button = new SciFiButton
            {
                MinSize = new Vector2(buttonSize, buttonSize),
                NormalColor = color,
                TextColor = revealed ? SweepNumberColors[Math.Clamp(value, 0, 8)] : Color.White,
                Disabled = revealed,
                Text = text,
            };
            button.UpdateVisual();
            button.OnPressed += () => OnSweepCellPressed(index);
            PuzzleGrid.AddChild(button);
        }
    }

    private void OnSweepCellPressed(int index)
    {
        if (_sweepFlagMode)
        {
            if (!_sweepFlags.Remove(index))
                _sweepFlags.Add(index);

            if (_lastState != null)
                BuildMineSweepGrid(_lastState);
            return;
        }

        if (_sweepFlags.Contains(index))
            return;

        OnGridClick?.Invoke(index);
    }

    private void UpdateSweepFlagButtonText()
    {
        _sweepFlagButton.Text = Loc.GetString(_sweepFlagMode ? "disk-decryptor-sweep-flag-on" : "disk-decryptor-sweep-flag-off").ToUpperInvariant();
        _sweepFlagButton.UpdateVisual();
    }

    private void BuildFlowNetwork(DiskDecryptorBoundUserInterfaceState state)
    {
        FlowCanvas.RemoveAllChildren();
        GridHintLabel.Text = Loc.GetString("disk-decryptor-flow-hint");

        var size = state.FlowSize;
        var open = state.FlowOpen ?? new List<bool>();
        var checkpoints = state.FlowCheckpoints ?? new List<int>();
        var path = state.FlowPath ?? new List<int>();
        var nextCheckpoint = state.FlowNextCheckpoint;
        var current = path.Count > 0 ? path[^1] : state.FlowStartIndex;

        GridInfoLabel.Text = Loc.GetString("disk-decryptor-flow-progress", ("done", nextCheckpoint), ("total", checkpoints.Count));

        const float cellSize = 26f;
        const float gap = 20f;
        const float pitch = cellSize + gap;
        FlowCanvasTrack.MinSize = new Vector2(size * pitch, size * pitch);

        for (var i = 0; i < open.Count; i++)
        {
            if (!open[i])
                continue;

            var x = i % size;
            var y = i / size;

            if (x < size - 1 && open[i + 1])
                AddFlowEdge(x, y, x + 1, y, pitch, cellSize, IsTracedEdge(path, i, i + 1));
            if (y < size - 1 && open[i + size])
                AddFlowEdge(x, y, x, y + 1, pitch, cellSize, IsTracedEdge(path, i, i + size));
        }

        for (var i = 0; i < open.Count; i++)
        {
            if (!open[i])
                continue;

            var index = i;
            var x = i % size;
            var y = i / size;
            var checkpointIndex = checkpoints.IndexOf(i);
            var isCheckpoint = checkpointIndex >= 0;
            var isHit = isCheckpoint && checkpointIndex < nextCheckpoint;
            var color = i == current ? FlowCurrent
                : isHit ? FlowCheckpointHit
                : isCheckpoint ? FlowCheckpointPending
                : i == state.FlowStartIndex ? FlowStartColor
                : path.Contains(i) ? FlowVisited
                : FlowNodeIdle;
            var node = new SciFiButton
            {
                MinSize = new Vector2(cellSize, cellSize),
                NormalColor = color,
                TextColor = Color.Black,
                Text = isCheckpoint ? (checkpointIndex + 1).ToString() : string.Empty,
            };
            node.UpdateVisual();
            node.OnPressed += () => OnGridClick?.Invoke(index);
            LayoutContainer.SetPosition(node, new Vector2(x * pitch, y * pitch));
            FlowCanvas.AddChild(node);
        }
    }

    private static bool IsTracedEdge(List<int> path, int a, int b)
    {
        for (var i = 0; i < path.Count - 1; i++)
        {
            if ((path[i] == a && path[i + 1] == b) || (path[i] == b && path[i + 1] == a))
                return true;
        }

        return false;
    }

    private void AddFlowEdge(int x0, int y0, int x1, int y1, float pitch, float cellSize, bool traced)
    {
        const float thickness = 4f;
        var color = traced ? FlowTracedLine : FlowIdleLine;

        Vector2 pos, size;
        if (y0 == y1)
        {
            pos = new Vector2(x0 * pitch + cellSize, y0 * pitch + cellSize / 2f - thickness / 2f);
            size = new Vector2(pitch - cellSize, thickness);
        }
        else
        {
            pos = new Vector2(x0 * pitch + cellSize / 2f - thickness / 2f, y0 * pitch + cellSize);
            size = new Vector2(thickness, pitch - cellSize);
        }

        var bar = new PanelContainer
        {
            PanelOverride = new StyleBoxFlat { BackgroundColor = color },
            MinSize = size,
        };
        LayoutContainer.SetPosition(bar, pos);
        FlowCanvas.AddChild(bar);
    }

    private void BuildBreachGrid(DiskDecryptorBoundUserInterfaceState state)
    {
        PuzzleGrid.Columns = Math.Max(1, state.BreachSize);
        GridHintLabel.Text = Loc.GetString("disk-decryptor-breach-hint");
        GridInfoLabel.Text = Loc.GetString("disk-decryptor-breach-buffer", ("moves", state.BreachMovesLeft));

        var codes = state.BreachCodes ?? new List<string>();
        var path = state.BreachPath ?? new List<int>();
        var sequence = state.BreachSequence ?? new List<string>();
        var size = state.BreachSize;
        var buttonSize = GridButtonSize(size);

        var matchedTail = 0;
        for (var len = Math.Min(sequence.Count, path.Count); len > 0; len--)
        {
            var offset = path.Count - len;
            var ok = true;
            for (var i = 0; i < len; i++)
            {
                if (codes.Count <= path[offset + i] || codes[path[offset + i]] != sequence[i])
                {
                    ok = false;
                    break;
                }
            }
            if (ok)
            {
                matchedTail = len;
                break;
            }
        }

        SequenceRow.RemoveAllChildren();
        for (var i = 0; i < sequence.Count; i++)
        {
            var done = i < matchedTail;
            SequenceRow.AddChild(new Label
            {
                Text = sequence[i],
                FontColorOverride = done ? BreachSequenceDone : TextDim,
            });
        }

        for (var i = 0; i < codes.Count; i++)
        {
            var index = i;
            var inPath = path.Contains(index);
            var legal = !inPath && IsLegalBreachMoveClientSide(size, path, index);
            var color = inPath ? BreachPicked : legal ? BreachLegal : BreachIdle;
            AddGridButton(index, color, inPath, codes[index], buttonSize);
        }
    }

    // mirrors the server's legality check, just to highlight legal cells
    private static bool IsLegalBreachMoveClientSide(int size, List<int> path, int index)
    {
        if (path.Count == 0)
            return index / size == 0;

        var last = path[^1];
        var needColumn = path.Count % 2 == 1;
        return needColumn ? index % size == last % size : index / size == last / size;
    }

    // bigger grids get smaller buttons so the window doesn't keep growing
    private static float GridButtonSize(int gridSize) => Math.Clamp(280f / Math.Max(1, gridSize), 28f, 48f);

