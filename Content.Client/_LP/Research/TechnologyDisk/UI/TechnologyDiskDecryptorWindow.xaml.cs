    private void BuildFrequencyBands(DiskDecryptorBoundUserInterfaceState state)
    {
        GridHintLabel.Text = Loc.GetString("disk-decryptor-bands-hint");

        var periods = state.BandsPeriod ?? new List<float>();
        var zoneStarts = state.BandsZoneStart ?? new List<float>();
        var zoneWidths = state.BandsZoneWidth ?? new List<float>();
        var startTimes = state.BandsStartTime ?? new List<TimeSpan>();
        var solved = state.BandsSolved ?? new List<bool>();

        GridInfoLabel.Text = Loc.GetString("disk-decryptor-bands-progress", ("done", solved.Count(s => s)), ("total", periods.Count));

        BandsContainer.RemoveAllChildren();
        _bandRows.Clear();

        for (var i = 0; i < periods.Count; i++)
        {
            var index = i;
            var solvedThis = solved.Count > i && solved[i];
            var wrapper = new PanelContainer { MinSize = new Vector2(1, 34), HorizontalExpand = true };
            var layout = new LayoutContainer();
            wrapper.AddChild(layout);

