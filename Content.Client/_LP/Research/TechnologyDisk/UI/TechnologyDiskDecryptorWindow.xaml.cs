    {
        var button = new SciFiButton
        {
            MinSize = new Vector2(size, size),
            NormalColor = color,
            TextColor = Color.White,
            Disabled = disabled,
            Text = text,
        };
        button.UpdateVisual();
        button.OnPressed += () => OnGridClick?.Invoke(index);
        PuzzleGrid.AddChild(button);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        // wrap the time so sin() doesn't lose precision after hours of uptime
        var time = (float)(_gameTiming.CurTime.TotalSeconds % 1000.0);

        // slow, continuous sweep on the three big panels, each offset so they don't move in lockstep. Runs regardless of phase, it's just ambiance.
        const float sweepSeconds = 5f;
        _masterFrame!.ScanlinePosition = (time % (sweepSeconds * 1.5f)) / (sweepSeconds * 1.5f);
        for (var i = 0; i < _sectionFrames.Count; i++)
        {
            var offset = sweepSeconds * i / _sectionFrames.Count;
            _sectionFrames[i].ScanlinePosition = ((time + offset) % sweepSeconds) / sweepSeconds;
        }

        if (_phase == DecryptorPhase.Idle || _secondsTotal <= 0f)
        {
            _timeFillBox.BackgroundColor = TrackColor;
            _timeFill!.MinSize = Vector2.Zero;
            return;
        }

        var remaining = Math.Clamp((float)(_deadline - _gameTiming.CurTime).TotalSeconds, 0f, _secondsTotal);
        var fraction = remaining / _secondsTotal;
        var trackWidth = TrackWidthOf(TimeBarTrack);
        var trackHeight = TimeBarTrack.Size.Y > 1f ? TimeBarTrack.Size.Y : 16f;
        _timeFill!.MinSize = new Vector2(trackWidth * fraction, trackHeight);
        LayoutContainer.SetPosition(_timeFill, Vector2.Zero);

        // color only depends on the fraction, not on time, nothing here oscillates, so there's nothing left that could read as flicker
        _timeFillBox.BackgroundColor = GetBarColor(fraction);

        if (_phase == DecryptorPhase.Manual && _minigameKind == MinigameKind.Calibration && _markerRect != null)
        {
            var calibrationTrackWidth = TrackWidthOf(CalibrationTrack);
            var calibrationTrackHeight = CalibrationTrack.Size.Y > 1f ? CalibrationTrack.Size.Y : 40f;
            var position = GetCalibrationMarkerPosition(_gameTiming.CurTime);
            var x = position * (calibrationTrackWidth - MarkerWidth);

            _markerRect.MinSize = new Vector2(MarkerWidth, calibrationTrackHeight);
            LayoutContainer.SetPosition(_markerRect, new Vector2(x, 0));

            // gentle breathing glow so the marker reads as "live" rather than a static block sliding along a rail
            var pulse = 0.5f + 0.5f * MathF.Sin(time * 5f);
            _markerBox.BackgroundColor = LerpColor(MarkerColor, Color.White, pulse * 0.35f);
        }

        // Pattern Recall: hide the still-showing targets the instant the reveal window ends.
        if (_patternRevealing && _gameTiming.CurTime >= _patternRevealEnd)
        {
            _patternRevealing = false;
            foreach (var button in _patternButtons)
            {
                button.NormalColor = PatternHidden;
                button.Disabled = false;
                button.UpdateVisual();
            }
        }

        // Frequency Bands: same idea as the single Calibration marker, just once per active row.
        foreach (var (wrapper, zone, marker, markerBox, clickCatcher, period, startTime, zoneStart, zoneWidth) in _bandRows)
        {
            var trackW = TrackWidthOf(wrapper);
            var trackH = wrapper.Size.Y > 1f ? wrapper.Size.Y : 34f;

            clickCatcher.MinSize = new Vector2(trackW, trackH);

            zone.MinSize = new Vector2(zoneWidth * trackW, trackH);
            LayoutContainer.SetPosition(zone, new Vector2(zoneStart * trackW, 0));

            var position = GetBandPositionClientSide(period, startTime, _gameTiming.CurTime);
            marker.MinSize = new Vector2(MarkerWidth, trackH);
            LayoutContainer.SetPosition(marker, new Vector2(position * (trackW - MarkerWidth), 0));

            var pulse = 0.5f + 0.5f * MathF.Sin(time * 5f);
            markerBox.BackgroundColor = LerpColor(MarkerColor, Color.White, pulse * 0.35f);
        }
    }

    // Mirrors TechnologyDiskDecryptorSystem.GetBandPosition on the server.
    private static float GetBandPositionClientSide(float period, TimeSpan startTime, TimeSpan now)
    {
        if (period <= 0f)
            return 0f;

        var cycle = period * 2f;
        var t = (float)(now - startTime).TotalSeconds % cycle;
        if (t < 0f)
            t += cycle;

        return t < period ? t / period : 2f - t / period;
    }

    // Mirrors TechnologyDiskDecryptorSystem.GetCalibrationMarkerPosition on the server -
    // both sides work out the marker position independently from the same start time and
    // period instead of the server pushing a position every frame.
    private float GetCalibrationMarkerPosition(TimeSpan now)
    {
        var period = _calibrationPeriod;
        if (period <= 0f)
            return 0f;

        var elapsed = (float)(now - _calibrationStartTime).TotalSeconds;
        var cycle = period * 2f;
        var t = elapsed % cycle;
        if (t < 0f)
            t += cycle;

        return t < period ? t / period : 2f - t / period;
    }

    private static Color LerpColor(Color a, Color b, float t)
    {
        t = Math.Clamp(t, 0f, 1f);
        return new Color(a.R + (b.R - a.R) * t, a.G + (b.G - a.G) * t, a.B + (b.B - a.B) * t, 1f);
    }

    // green while there's plenty left, sliding through amber and into red as it gets
    // critical - shared by both the timer and the integrity bar
    private static Color GetBarColor(float fraction)
    {
        return fraction > 0.5f
            ? LerpColor(Color.Gold, Color.LimeGreen, (fraction - 0.5f) * 2f)
            : LerpColor(Color.Red, Color.Gold, fraction * 2f);
    }
